"""Balance of retrofitted and comparison buildings within facility type (Table 2)."""
import os, sys, time
import numpy as np, pandas as pd
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, PROC, RES
from s03_energy import ym_add, ym_range
import s04_analysis as A

USES = [("보건", "health_centre"), ("어린이집", "daycare")]
VARS = [("Floor area (m$^2$)", "area_m2", "cont", 0), ("Built year", "built", "cont", 0),
        ("Pre-period electricity (kWh/m$^2\\cdot$y)", "eui_pre", "cont", 1), ("Gas meter confirmed (\\%)", "gas_meter", "share", 0),
        ("Coldest climate zone (\\%)", "zone_c1", "share", 0)]


def smd(t, c, kind):
    t, c = t.dropna(), c.dropna()
    if not len(t) or not len(c): return np.nan
    vt = t.mean() * (1 - t.mean()) if kind == "share" else t.var(ddof=1); vc = c.mean() * (1 - c.mean()) if kind == "share" else c.var(ddof=1)
    den = np.sqrt((vt + vc) / 2)
    return float((t.mean() - c.mean()) / den) if den > 0 else (0.0 if t.mean() == c.mean() else np.nan)


def main():
    B, E = A.load()
    S = A.imputation_setup(B, E, "elec", **A.PRIMARY_IMP)
    cols = ["use", "variable", "kind", "n_T", "n_C", "mean_T", "sd_T", "mean_C", "sd_C", "smd"]
    if S is None:
        pd.DataFrame(columns=cols).to_csv(RES / "a_balance_within.csv", index=False); print("no treated rows"); return
    f = S["fit"](); D = S["D"]
    tp = set(S["pids"][pd.unique(S["pi"][S["post"] & f["ok"]])]); cp = set(S["pids"][pd.unique(S["pi"][f["F"] & S["isc"]])])
    X = B[B.pid.isin(tp | cp)].drop_duplicates("pid").copy(); X["grp"] = np.where(X.pid.isin(tp), "T", "C")
    X["built"] = pd.to_numeric(X.built_year.astype(str).str[:4], errors="coerce")
    X["zone_c1"] = (X.zone == "중부1_춘천").astype(float)
    raw = pd.read_csv(PROC / "energy_monthly.csv"); gas_ok = set(raw[(raw.carrier == "gas") & (raw.status == "ok")].pid)
    X["gas_meter"] = X.pid.isin(gas_ok).astype(float)
    pint, _ = A.pre_intensity(B, E, "elec")
    Fc = D[f["F"] & S["isc"]].sort_values("ym").groupby("pid").tail(12)
    g = Fc.groupby("pid").agg(n=("kwh", "size"), m=("kwh", "mean"), area=("gr_gfa", "first"))
    cint = (12 * g.m / g.area)[g.n >= A.MIN_WIN]
    X["eui_pre"] = np.where(X.grp == "T", X.pid.map(pint), X.pid.map(cint))
    nm = X.name_list.astype(str)
    X["subtype"] = np.where(nm.str.contains("진료소"), "post", np.where(nm.str.contains("지소"), "sub_centre", "other"))
    rows = []
    for u, en in USES:
        T, C = X[(X.use_class == u) & (X.grp == "T")], X[(X.use_class == u) & (X.grp == "C")]
        rows.append(dict(use=en, variable="Buildings", kind="count", n_T=len(T), n_C=len(C)))
        for name, col, kind, _ in VARS:
            t, c = T[col].dropna(), C[col].dropna()
            sd = lambda x: (np.sqrt(x.mean() * (1 - x.mean())) if kind == "share" else x.std(ddof=1)) if len(x) > 1 else np.nan
            rows.append(dict(use=en, variable=name, kind=kind, n_T=len(t), n_C=len(c), mean_T=t.mean() if len(t) else np.nan, sd_T=sd(t),
                             mean_C=c.mean() if len(c) else np.nan, sd_C=sd(c), smd=smd(t, c, kind)))
    T, C = X[(X.use_class == "보건") & (X.grp == "T")], X[(X.use_class == "보건") & (X.grp == "C")]
    SUB = [("Primary health-care post (\\%)", "post"), ("Health sub-centre (\\%)", "sub_centre"), ("Other health centre (\\%)", "other")]
    for name, key in SUB:
        t, c = (T.subtype == key).astype(float), (C.subtype == key).astype(float)
        rows.append(dict(use="health_centre", variable=name, kind="share", n_T=len(t), n_C=len(c), mean_T=t.mean() if len(t) else np.nan,
                         sd_T=np.sqrt(t.mean() * (1 - t.mean())) if len(t) else np.nan, mean_C=c.mean() if len(c) else np.nan,
                         sd_C=np.sqrt(c.mean() * (1 - c.mean())) if len(c) else np.nan, smd=smd(t, c, "share")))
    R = pd.DataFrame(rows).reindex(columns=cols); R.to_csv(RES / "a_balance_within.csv", index=False)
    def cell(v, kind, dec):
        if pd.isna(v): return "--"
        return f"{100 * v:.0f}" if kind == "share" else (f"{v:.{dec}f}" if dec else f"{v:.0f}")
    L = [f"% Auto-generated by src/a_balance_within.py from results/a_balance_within.csv on {time.strftime('%Y-%m-%d %H:%M')} -- do not edit by hand.",
         "% Columns: health centres (treated, control pool, SMD), daycare centres (treated, control pool, SMD). n for the intensity row is in the csv."]
    get = lambda en, var: R[(R.use == en) & (R.variable == var)].iloc[0]
    L.append("Buildings & " + " & ".join(f"{int(get(en, 'Buildings').n_T)} & {int(get(en, 'Buildings').n_C)} & " for _, en in USES).rstrip("& ").rstrip() + r" & \\")
    for name, col, kind, dec in VARS:
        cells = []
        for _, en in USES:
            r = get(en, name); cells += [cell(r.mean_T, kind, dec), cell(r.mean_C, kind, dec), "--" if pd.isna(r.smd) else f"{r.smd:+.2f}"]
        L.append(f"{name} & " + " & ".join(cells) + r" \\")
    for name, key in SUB:
        r = get("health_centre", name)
        L.append(f"{name} & {cell(r.mean_T, 'share', 0)} & {cell(r.mean_C, 'share', 0)} & " + ("--" if pd.isna(r.smd) else f"{r.smd:+.2f}") + r" & & & \\")
    (ROOT / "paper/figs").mkdir(parents=True, exist_ok=True)
    (ROOT / "paper/figs/a_balance_within.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    pd.set_option("display.width", 220); print(R.round(3).to_string(index=False)); print("\n".join(L))

if __name__ == "__main__":
    main()
